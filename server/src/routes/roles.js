const router=require('express').Router();
const {requireAuth}=require('../middleware/auth');
const ctrl=require('../controllers/roleController');
router.use(requireAuth);
router.use((req,res,next)=>req.method==='GET'?next():res.status(405).json({success:false,message:'Roles are fixed: Admin, User and Manager. Role creation and editing are unavailable.'}));
router.get('/catalog',ctrl.list);
router.get('/assignable',ctrl.list);
router.get('/',ctrl.list);
router.get('/:key/history',ctrl.history);
module.exports=router;
