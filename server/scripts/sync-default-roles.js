// Keep standalone SQL installation equivalent to the application's default definitions.
const fs = require('node:fs');
const path = require('node:path');
const roles = require('../src/access/defaultRoles');
const { catalog } = require('../src/access/catalog');
const { managerUpgradeSQL } = require('../src/access/teamUsers');
const quote = value => "'" + value.replaceAll("'", "''") + "'";
const begin = '-- BEGIN GENERATED DEFAULT ROLES';
const end = '-- END GENERATED DEFAULT ROLES';
const block = `${begin}\n-- Generated by server/scripts/sync-default-roles.js. Existing names, keys and edits are preserved.\nALTER TABLE access_roles ADD COLUMN IF NOT EXISTS is_default BOOLEAN NOT NULL DEFAULT FALSE;\nINSERT INTO access_roles(key,name,responsibility,permissions,assignable_roles,is_default) VALUES\n${roles.map(r => ` (${[r.key, r.name, r.responsibility, JSON.stringify(r.permissions), JSON.stringify(r.assignable_roles)].map(quote).join(',')},TRUE)`).join(',\n')}\nON CONFLICT DO NOTHING;\nUPDATE access_roles SET permissions=${quote(JSON.stringify(Object.fromEntries(catalog.map(p=>[p.key,'all']))))}::jsonb WHERE key='admin';\n${managerUpgradeSQL}\n${end}`;
const file = path.join(__dirname, '../../database/schema.sql');
const schema = fs.readFileSync(file, 'utf8');
const updated = schema.includes(begin)
  ? schema.replace(new RegExp(begin + '[\\s\\S]*?' + end), () => block)
  : schema.replace('ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;', block + '\nALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;');
if (process.argv.includes('--check')) {
  if (schema !== updated) throw new Error('Default role SQL is stale. Run node server/scripts/sync-default-roles.js');
  console.log('Default role SQL matches application definitions.');
} else fs.writeFileSync(file, updated);
